import numpy as np

# Создаем пустую текстовую матрицу 3x4 (3 строки, 4 столбца)
# Чтобы покрыть индексы строк 0..2 и столбцов 0..3
grid = np.full((3, 4), "[ ]")

# Задаем координаты траектории (row, col)
# Старт в (0,0), шаг Δy=+2, Δx=+3 -> финиш в (1,2)
# (В матрицах строка 0 обычно верхняя, но для графика мы считаем строку 2 верхней)
start_row, start_col = 1, 0  # Снизу слева
end_row, end_col = 0, 2      # Сверху справа

grid[start_row, start_col] = "[*]"
grid[end_row, end_col] = "[*]"

# Печатаем матрицу построчно
for row in grid:
    print(" ".join(row))