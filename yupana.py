def generate_sine_on_triangular_grid(steps: int, amplitude: int = 100000):
    """
    Вычисление дискретного синуса в точках треугольного ряда (3-я строка Юпаны).
    Расчет идет исключительно через суммы и разности разностных регистров.
    """
    # Начальное распределение «камешков» по регистрам (строкам Юпаны)
    S = 0            # Регистр текущего значения синуса (Строка 1)
    V = amplitude    # Регистр скорости / первой разности (Строка 2)
    T = 0            # Регистр треугольных чисел / сетки эклиптики (Строка 3)
    
    # Коэффициент затухания разности (масштаб шага в целых числах)
    # Заменяет умножение на малый угол битовым сдвигом (деление на 64)
    shift_bit = 6
    
    results = []
    
    # Основной разностный цикл перекладывания
    for n in range(1, steps + 1):
        # 1. Шаг по сетке эклиптики (Строка 3 аккумулирует треугольные числа: 1, 3, 6, 10...)
        T = T + n
        
        # 2. Быстрый алгоритм знака без деления (Битовый сдвиг индекса n)
        # Имитирует циклическое движение маркера по 8 флагам первой строки Юпаны
        # Формирует последовательность попарных знаков: ++, --, ++, -- ...
        is_positive = ((n >> 1) & 1) == 0
        
        # 3. Перенос разностей между регистрами Юпаны (сложение и вычитание)
        # Величина приращения пропорциональна текущему синусу, сдвинутому по разрядам
        delta = S >> shift_bit
        
        if is_positive:
            V = V - delta  # Торможение/разворот волны при положительной фазе флага
        else:
            V = V + delta  # Ускорение волны при отрицательной фазе флага
            
        S = S + V          # Строка 1 аккумулирует скорость из Строки 2
        
        results.append((n, T, S))
        
    return results

# Запуск алгоритма на 12 шагов вперед
sin_table = generate_sine_on_triangular_grid(steps=12)

# Вывод результатов в виде таблицы состояний регистров Юпаны
print(f"{'Шаг n':<7} | {'Треуг. число T (Сетка)':<22} | {'Значение Синуса S (Строка 1)'}")
print("-" * 65)
for n, T, S in sin_table:
    print(f"{n:<7} | {T:<22} | {S:<20}")


def count_operations(steps: int):
    # Analyzing operations per iteration for 1 step (coefficient calculation)
    # 1. T = T + n -> 1 addition
    # 2. (n >> 1) & 1 -> 1 shift, 1 bitwise AND, 1 comparison
    # 3. delta = S >> shift_bit -> 1 shift
    # 4. V = V - delta or V = V + delta -> 1 addition/subtraction
    # 5. S = S + V -> 1 addition
    
    # Total arithmetic/logical ops per coefficient per step is minimal.
    # Let's count how many additions/shifts per step.
    ops_per_step = {
        "additions_subtractions": 3,
        "bitwise_shifts": 2,
        "bitwise_and": 1
    }
    return ops_per_step

