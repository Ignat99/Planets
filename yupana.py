def generate_two_loop_sine_yupana(steps: int, amplitude: int = 100000):
    """
    Разностный алгоритм в стиле Юпаны с двумя независимыми циклами.
    1-й цикл: Колебание Луны (быстрое)
    2-й цикл: Средняя аномалия Солнца M (медленное годовое колебание)
    Расчет идет исключительно через целочисленные сложения, вычитания и сдвиги.
    """
    # === КОНТУР ЛУНЫ (Быстрый регистр) ===
    S_moon = 0
    V_moon = amplitude
    T = 0
    shift_moon = 6  # Битовый сдвиг для масштабирования лунной волны (деление на 64)
    
    # === КОНТУР СОЛНЦА (Медленный регистр для аномалии M) ===
    S_sun = 0
    # Начальная скорость для контура Солнца (задает амплитуду ~0.05' относительно Луны)
    V_sun = amplitude >> 2  
    # Битовый сдвиг для макро-колебания Солнца (деление на 512, так как влияние слабее)
    shift_sun = 9  
    
    results = []
    
    for n in range(1, steps + 1):
        # ----------------------------------------------------
        # ШАГ 1: Расчет сетки эклиптики (Треугольные числа)
        # ----------------------------------------------------
        T = T + n
        
        # ----------------------------------------------------
        # ШАГ 2: Контур Луны (Быстрое попарное переключение флагов: ++, --, ++, --)
        # ----------------------------------------------------
        moon_positive = ((n >> 1) & 1) == 0
        delta_moon = S_moon >> shift_moon
        
        if moon_positive:
            V_moon = V_moon - delta_moon
        else:
            V_moon = V_moon + delta_moon
            
        S_moon = S_moon + V_moon
        
        # ----------------------------------------------------
        # ШАГ 3: Контур Солнца (Медленное переключение флагов аномалии M)
        # Для имитации медленного годового периода знак переключается каждые 8 шагов
        # (вместо деления используем сдвиг индекса n на 3 бита вправо)
        # ----------------------------------------------------
        sun_positive = ((n >> 3) & 1) == 0
        delta_sun = S_sun >> shift_sun
        
        if sun_positive:
            V_sun = V_sun - delta_sun
        else:
            V_sun = V_sun + delta_sun
            
        S_sun = S_sun + V_sun
        
        # ----------------------------------------------------
        # ШАГ 4: Слияние двух строк Юпаны в итоговый Синус
        # Камешки из обоих независимых контуров ссыпаются в один общий результат
        # ----------------------------------------------------
        S_total = S_moon + S_sun
        
        results.append((n, T, S_moon, S_sun, S_total))
        
    return results

# Тестовый запуск на 24 шага, чтобы увидеть, как медленный контур Солнца меняет фазу
yupana_table = generate_two_loop_sine_yupana(steps=24)

# Вывод результатов
print(f"{'Шаг n':<6} | {'Сетка T':<8} | {'Контур Луны':<13} | {'Контур Солнца (M)':<17} | {'Итог Синус S'}")
print("-" * 70)
for n, T, S_m, S_s, S_tot in yupana_table:
    print(f"{n:<6} | {T:<8} | {S_m:<13} | {S_s:<17} | {S_tot:<12}")
