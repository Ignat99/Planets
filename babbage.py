class DifferenceEngineSimulation:
    def __init__(self, y0, d1, d2):
        # Инициализация колонок (регистров) машины
        self.y = y0       # Колонка результата (значение функции)
        self.d1 = d1     # Колонка первой разности
        self.d2 = d2     # Колонка второй разности (константа для x^2)
        self.step = 0

    def turn_crank(self):
        """Один оборот рукоятки выполняет последовательные сложения"""
        self.step += 1
        
        # В реальной машине №2 сложения идут параллельно-последовательно,
        # но математический итог за один цикл выглядит так:
        self.y += self.d1
        self.d1 += self.d2
        
        # Ограничение разрядности (оригинал работал с 31-значными числами)
        self.y %= 10**31
        self.d1 %= 10**31

    def display(self):
        print(f"Шаг {self.step:2d} | Y (Результат): {self.y:<5} | Δ¹: {self.d1:<5} | Δ²: {self.d2:<5}")

# --- НАСТРОЙКА И ЗАПУСК СИМУЛЯЦИИ ---
# Для функции y = x^2 + x + 41 при x=0:
# y(0) = 41
# y(1) = 43  -> первая разность d1 = y(1) - y(0) = 2
# y(2) = 47  -> вторая разность d2 = (47-43) - (43-41) = 2 (постоянная)

print("--- Старт симуляции Разностной Машины Бэббиджа ---")
engine = DifferenceEngineSimulation(y0=41, d1=2, d2=2)
print(f"Старт  | Y (Результат): 41    | Δ¹: 2     | Δ²: 2")

for _ in range(5):
    engine.turn_crank()
    engine.display()
